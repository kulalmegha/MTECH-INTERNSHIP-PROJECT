def _to_utc(dt: Optional[datetime]) -> Optional[datetime]:
    if dt is None:
        return None
    if dt.tzinfo is None:
        return dt.replace(tzinfo=timezone.utc)
    return dt


def _build_trend_chart_image(checkins: List[Checkin]) -> Optional[io.BytesIO]:
    """Generate a Matplotlib distress trajectory trend chart in-memory."""
    if not checkins:
        return None

    dates = [_to_utc(c.created_at) for c in checkins]
    scores = [c.distress_score if c.distress_score is not None else 0.0 for c in checkins]

    fig, ax = plt.subplots(figsize=(7.2, 3.2), dpi=150)
    fig.patch.set_facecolor("#ffffff")
    ax.set_facecolor("#f8fafc")

    # Background risk bands
    ax.axhspan(70, 100, color="#fee2e2", alpha=0.6, label="High Distress (70–100)")
    ax.axhspan(35, 70, color="#fef3c7", alpha=0.6, label="Moderate Distress (35–70)")
    ax.axhspan(0, 35, color="#dcfce7", alpha=0.6, label="Low Distress (0–35)")

    # Plot trendline
    ax.plot(dates, scores, color="#2563eb", linewidth=2.2, marker="o", markersize=6, label="Distress Score")

    # Annotate points
    for d, s in zip(dates, scores):
        ax.annotate(
            f"{s:.1f}",
            (d, s),
            textcoords="offset points",
            xytext=(0, 8),
            ha="center",
            fontsize=8,
            fontweight="bold",
            color="#1e293b",
        )

    ax.set_ylim(-2, 105)
    ax.set_ylabel("Distress Score (0–100)", fontsize=9, fontweight="bold", color="#334155")
    ax.set_title("Longitudinal Distress Score Trajectory", fontsize=11, fontweight="bold", color="#0f172a", pad=10)
    ax.grid(True, linestyle="--", alpha=0.4, color="#cbd5e1")
    ax.tick_params(colors="#475569", labelsize=8)

    # Format dates
    if len(dates) > 1:
        ax.xaxis.set_major_formatter(mdates.DateFormatter("%b %d\n%H:%M"))
    else:
        ax.xaxis.set_major_formatter(mdates.DateFormatter("%b %d"))

    ax.legend(loc="upper left", fontsize=7.5, framealpha=0.85)
    plt.tight_layout()

    buf = io.BytesIO()
    plt.savefig(buf, format="png", dpi=150, bbox_inches="tight")
    plt.close(fig)
    buf.seek(0)
    return buf


def _build_caseload_pie_chart(counts: dict) -> Optional[io.BytesIO]:
    """Generate a caseload distribution pie/donut chart in-memory."""
    labels = ["High Band", "Moderate Band", "Low Band", "No Check-ins"]
    values = [counts.get("high", 0), counts.get("moderate", 0), counts.get("low", 0), counts.get("none", 0)]
    palette = ["#ef4444", "#f59e0b", "#10b981", "#94a3b8"]

    # Filter out zeros
    filtered_data = [(l, v, c) for l, v, c in zip(labels, values, palette) if v > 0]
    if not filtered_data:
        return None

    plot_labels = [x[0] for x in filtered_data]
    plot_vals = [x[1] for x in filtered_data]
    plot_colors = [x[2] for x in filtered_data]

    fig, ax = plt.subplots(figsize=(4.5, 2.6), dpi=150)
    fig.patch.set_facecolor("#ffffff")
    wedges, texts, autotexts = ax.pie(
        plot_vals,
        labels=plot_labels,
        colors=plot_colors,
        autopct="%1.0f%%",
        startangle=140,
        textprops=dict(color="#1e293b", fontsize=8),
        wedgeprops=dict(width=0.45, edgecolor="w", linewidth=1.5),
    )
    for autotext in autotexts:
        autotext.set_fontsize(8)
        autotext.set_fontweight("bold")

    ax.set_title("Caseload Distress Risk Distribution", fontsize=10, fontweight="bold", color="#0f172a")
    plt.tight_layout()

    buf = io.BytesIO()
    plt.savefig(buf, format="png", dpi=150, bbox_inches="tight")
    plt.close(fig)
    buf.seek(0)
    return buf


@router.get("/cases/{case_code}/report", response_class=Response)
async def generate_case_report(
    case_code: str,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(require_role("counsellor")),
):
    """Generate and return a clinical PDF dossier for a single case."""
    # 1. Fetch case
    query = (
        select(Case)
        .where(Case.case_code == case_code)
        .options(
            selectinload(Case.checkins),
            selectinload(Case.alerts),
            selectinload(Case.actions),
        )
    )
    result = await db.execute(query)
    case = result.scalar_one_or_none()

    if not case:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=f"Case {case_code} not found")
    if case.assigned_counsellor_id != current_user.id:
        raise HTTPException(status_code=status.HTTP_403_FORBIDDEN, detail="Access denied to unassigned case")

    checkins = sorted(case.checkins, key=lambda c: _to_utc(c.created_at))
    alerts = sorted(case.alerts, key=lambda a: (ALERT_PRIORITIES.get(a.alert_type, 99), _to_utc(a.created_at)))
    actions = sorted(case.actions, key=lambda a: _to_utc(a.created_at), reverse=True)

    # 2. Setup ReportLab PDF document
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=36,
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "ReportTitle",
        parent=styles["Heading1"],
        fontSize=18,
        leading=22,
        textColor=colors.HexColor("#0f172a"),
        fontName="Helvetica-Bold",
        spaceAfter=4,
    )
    sub_title_style = ParagraphStyle(
        "SubTitle",
        parent=styles["Normal"],
        fontSize=9,
        leading=12,
        textColor=colors.HexColor("#64748b"),
        spaceAfter=12,
    )
    section_h2 = ParagraphStyle(
        "SectionH2",
        parent=styles["Heading2"],
        fontSize=12,
        leading=15,
        textColor=colors.HexColor("#1e293b"),
        fontName="Helvetica-Bold",
        spaceBefore=14,
        spaceAfter=6,
    )
    cell_style = ParagraphStyle(
        "Cell",
        parent=styles["Normal"],
        fontSize=8,
        leading=10,
        textColor=colors.HexColor("#1e293b"),
    )
    cell_bold = ParagraphStyle(
        "CellBold",
        parent=styles["Normal"],
        fontSize=8,
        leading=10,
        fontName="Helvetica-Bold",
        textColor=colors.HexColor("#0f172a"),
    )
    disclaimer_style = ParagraphStyle(
        "Disclaimer",
        parent=styles["Normal"],
        fontSize=7,
        leading=9.5,
        textColor=colors.HexColor("#64748b"),
        alignment=1,  # Centered
    )

    story = []

    # Title & Metadata Banner
    story.append(Paragraph("CLINICAL CASE PROGRESS REPORT", title_style))
    story.append(
        Paragraph(
            f"Case Identifier: <b>{case.case_code}</b> | Assigned Counsellor: <b>{current_user.username}</b> | "
            f"Generated: <b>{datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}</b>",
            sub_title_style,
        )
    )
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#cbd5e1"), spaceAfter=10))

    # Case Summary Box
    next_due_dt = _to_utc(case.next_follow_up_due)
    next_due_str = next_due_dt.strftime("%Y-%m-%d %H:%M UTC") if next_due_dt else "None"
    meta_data = [
        [
            Paragraph("<b>Case Status:</b> " + (case.status.value if hasattr(case.status, 'value') else str(case.status)).upper(), cell_style),
            Paragraph(f"<b>Follow-up Interval:</b> Every {case.follow_up_interval_days} days", cell_style),
            Paragraph(f"<b>Next Follow-up Due:</b> {next_due_str}", cell_style),
            Paragraph(f"<b>Total Check-ins:</b> {len(checkins)}", cell_style),
        ]
    ]
    t_meta = Table(meta_data, colWidths=[135, 135, 150, 120])
    t_meta.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f1f5f9")),
            ("PADDING", (0, 0), (-1, -1), 6),
            ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ])
    )
    story.append(t_meta)
    story.append(Spacer(1, 10))

    # Trend Chart
    chart_buf = _build_trend_chart_image(checkins)
    if chart_buf:
        story.append(Paragraph("Longitudinal Distress Trajectory", section_h2))
        img = RLImage(chart_buf, width=540, height=240)
        story.append(img)
        story.append(Spacer(1, 8))

    # Check-ins Table
    story.append(Paragraph(f"Check-in History ({len(checkins)} Entries)", section_h2))
    if checkins:
        headers = ["Date (UTC)", "Stress", "Safety / Threat", "Sentiment", "Emotion", "Distress Score", "Band"]
        rows = [[Paragraph(h, cell_bold) for h in headers]]
        for c in checkins:
            safety_flag = "Unsafe" if not c.feels_safe else "Safe"
            if c.faces_threat:
                safety_flag += " + Threat"
            sent_str = f"{c.sentiment_label or 'N/A'} ({c.sentiment_score:.2f})" if c.sentiment_score else (c.sentiment_label or "N/A")
            emo_str = f"{c.emotion_label or 'N/A'} ({c.emotion_score:.2f})" if c.emotion_score else (c.emotion_label or "N/A")
            score_str = f"{c.distress_score:.1f}" if c.distress_score is not None else "N/A"
            band_str = (c.distress_band or "N/A").upper()
            dt_str = _to_utc(c.created_at).strftime("%Y-%m-%d %H:%M")

            rows.append([
                Paragraph(dt_str, cell_style),
                Paragraph(f"{c.stress_level}/10", cell_style),
                Paragraph(safety_flag, cell_style),
                Paragraph(sent_str, cell_style),
                Paragraph(emo_str, cell_style),
                Paragraph(score_str, cell_bold),
                Paragraph(band_str, cell_style),
            ])

        t_checkins = Table(rows, colWidths=[80, 45, 95, 95, 95, 70, 60])
        t_checkins.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e2e8f0")),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ])
        )
        story.append(t_checkins)
    else:
        story.append(Paragraph("<i>No check-ins recorded yet for this case.</i>", cell_style))

    story.append(Spacer(1, 10))

    # Alerts Table
    story.append(Paragraph(f"Clinical Alerts ({len(alerts)} Triggered)", section_h2))
    if alerts:
        a_headers = ["Priority", "Type", "Status", "Triggered At", "Clinical Reason"]
        a_rows = [[Paragraph(h, cell_bold) for h in a_headers]]
        for a in alerts:
            prio = ALERT_PRIORITIES.get(a.alert_type, 4)
            p_badge = f"P{prio} (CRITICAL)" if prio == 1 else f"P{prio}"
            status_val = a.status.value if hasattr(a.status, 'value') else str(a.status)
            dt_str = _to_utc(a.created_at).strftime("%Y-%m-%d %H:%M")
            a_rows.append([
                Paragraph(p_badge, cell_bold),
                Paragraph(a.alert_type, cell_style),
                Paragraph(status_val.upper(), cell_style),
                Paragraph(dt_str, cell_style),
                Paragraph(a.reason or "Rule threshold reached.", cell_style),
            ])
        t_alerts = Table(a_rows, colWidths=[65, 85, 60, 80, 250])
        t_alerts.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e2e8f0")),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ])
        )
        story.append(t_alerts)
    else:
        story.append(Paragraph("<i>No alerts triggered for this case.</i>", cell_style))

    story.append(Spacer(1, 10))

    # Actions Taken Table
    story.append(Paragraph(f"Clinical Actions & Interventions ({len(actions)} Recorded)", section_h2))
    if actions:
        act_headers = ["Date (UTC)", "Channel", "Action Taken", "Outcome"]
        act_rows = [[Paragraph(h, cell_bold) for h in act_headers]]
        for act in actions:
            dt_str = _to_utc(act.created_at).strftime("%Y-%m-%d %H:%M")
            act_rows.append([
                Paragraph(dt_str, cell_style),
                Paragraph(act.contact_channel, cell_style),
                Paragraph(act.action_taken, cell_style),
                Paragraph(act.outcome or "Pending evaluation", cell_style),
            ])
        t_actions = Table(act_rows, colWidths=[80, 80, 200, 180])
        t_actions.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e2e8f0")),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ])
        )
        story.append(t_actions)
    else:
        story.append(Paragraph("<i>No clinical actions recorded yet.</i>", cell_style))

    story.append(Spacer(1, 16))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#cbd5e1"), spaceAfter=8))
    story.append(Paragraph(DISCLAIMER_TEXT, disclaimer_style))

    # Build PDF
    doc.build(story)
    pdf_bytes = buffer.getvalue()
    buffer.close()

    return Response(
        content=pdf_bytes,
        media_type="application/pdf",
        headers={"Content-Disposition": f'attachment; filename="case_report_{case_code}.pdf"'},
    )


@router.get("/reports/summary", response_class=Response)
async def generate_summary_report(
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(require_role("counsellor")),
):
    """Generate and return an overall caseload risk & triage summary PDF."""
    # 1. Fetch assigned cases
    q = (
        select(Case)
        .where(Case.assigned_counsellor_id == current_user.id)
        .options(
            selectinload(Case.checkins),
            selectinload(Case.alerts),
        )
    )
    cases = (await db.execute(q)).scalars().all()

    total_cases = len(cases)
    active_cases = [c for c in cases if (c.status.value if hasattr(c.status, 'value') else str(c.status)) == "active"]

    now = datetime.now(timezone.utc)
    overdue_count = sum(1 for c in active_cases if c.next_follow_up_due and _to_utc(c.next_follow_up_due) < now)

    # Risk band distribution
    band_counts = {"high": 0, "moderate": 0, "low": 0, "none": 0}
    for c in cases:
        if not c.checkins:
            band_counts["none"] += 1
        else:
            latest = sorted(c.checkins, key=lambda ch: _to_utc(ch.created_at))[-1]
            b = (latest.distress_band or "none").lower()
            if b in ("high", "higher"):
                band_counts["high"] += 1
            elif b == "moderate":
                band_counts["moderate"] += 1
            elif b == "low":
                band_counts["low"] += 1
            else:
                band_counts["none"] += 1

    # Open alerts count
    open_alerts = []
    for c in cases:
        for a in c.alerts:
            status_val = a.status.value if hasattr(a.status, 'value') else str(a.status)
            if status_val in ("open", "reviewed"):
                open_alerts.append(a)

    p1_count = sum(1 for a in open_alerts if ALERT_PRIORITIES.get(a.alert_type) == 1)
    p2_count = sum(1 for a in open_alerts if ALERT_PRIORITIES.get(a.alert_type) == 2)
    p3_count = sum(1 for a in open_alerts if ALERT_PRIORITIES.get(a.alert_type) == 3)
    p4_count = sum(1 for a in open_alerts if ALERT_PRIORITIES.get(a.alert_type) == 4)

    # 2. Build PDF Document
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=36,
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "SummaryTitle",
        parent=styles["Heading1"],
        fontSize=18,
        leading=22,
        textColor=colors.HexColor("#0f172a"),
        fontName="Helvetica-Bold",
        spaceAfter=4,
    )
    sub_title_style = ParagraphStyle(
        "SubTitle",
        parent=styles["Normal"],
        fontSize=9,
        leading=12,
        textColor=colors.HexColor("#64748b"),
        spaceAfter=12,
    )
    section_h2 = ParagraphStyle(
        "SectionH2",
        parent=styles["Heading2"],
        fontSize=12,
        leading=15,
        textColor=colors.HexColor("#1e293b"),
        fontName="Helvetica-Bold",
        spaceBefore=14,
        spaceAfter=6,
    )
    cell_style = ParagraphStyle(
        "Cell",
        parent=styles["Normal"],
        fontSize=8,
        leading=10,
        textColor=colors.HexColor("#1e293b"),
    )
    cell_bold = ParagraphStyle(
        "CellBold",
        parent=styles["Normal"],
        fontSize=8,
        leading=10,
        fontName="Helvetica-Bold",
        textColor=colors.HexColor("#0f172a"),
    )
    disclaimer_style = ParagraphStyle(
        "Disclaimer",
        parent=styles["Normal"],
        fontSize=7,
        leading=9.5,
        textColor=colors.HexColor("#64748b"),
        alignment=1,
    )

    story = []

    # Title & Metadata
    story.append(Paragraph("COUNSELLOR CASELOAD & TRIAGE SUMMARY REPORT", title_style))
    story.append(
        Paragraph(
            f"Supervising Counsellor: <b>{current_user.username}</b> | "
            f"Generated: <b>{now.strftime('%Y-%m-%d %H:%M UTC')}</b>",
            sub_title_style,
        )
    )
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#cbd5e1"), spaceAfter=10))

    # Metric Cards Table
    stats_data = [
        [
            Paragraph("<b>Total Active Cases</b>", cell_bold),
            Paragraph("<b>Open Alerts Queue</b>", cell_bold),
            Paragraph("<b>Overdue Follow-ups</b>", cell_bold),
            Paragraph("<b>High Distress Band</b>", cell_bold),
        ],
        [
            Paragraph(f"<font size=14><b>{len(active_cases)}</b></font>", cell_style),
            Paragraph(f"<font size=14 color='#ef4444'><b>{len(open_alerts)}</b></font>", cell_style),
            Paragraph(f"<font size=14 color='#3b82f6'><b>{overdue_count}</b></font>", cell_style),
            Paragraph(f"<font size=14 color='#f59e0b'><b>{band_counts['high']}</b></font>", cell_style),
        ],
    ]
    t_stats = Table(stats_data, colWidths=[135, 135, 135, 135])
    t_stats.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
            ("PADDING", (0, 0), (-1, -1), 8),
            ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
            ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ])
    )
    story.append(t_stats)
    story.append(Spacer(1, 10))

    # Alert Priority breakdown + Pie chart side by side
    pie_buf = _build_caseload_pie_chart(band_counts)

    alert_summary_data = [
        [Paragraph("<b>Alert Priority Level</b>", cell_bold), Paragraph("<b>Count</b>", cell_bold)],
        [Paragraph("P1 - Critical Safety Concerns", cell_style), Paragraph(str(p1_count), cell_bold)],
        [Paragraph("P2 - Explicit Counselling Requests", cell_style), Paragraph(str(p2_count), cell_bold)],
        [Paragraph("P3 - Acute Distress Increases (+20 pts)", cell_style), Paragraph(str(p3_count), cell_bold)],
        [Paragraph("P4 - Missed Scheduled Follow-ups", cell_style), Paragraph(str(p4_count), cell_bold)],
    ]
    t_alert_sum = Table(alert_summary_data, colWidths=[180, 50])
    t_alert_sum.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e2e8f0")),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
            ("PADDING", (0, 0), (-1, -1), 5),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ])
    )

    if pie_buf:
        chart_img = RLImage(pie_buf, width=280, height=160)
        split_table = Table([[t_alert_sum, chart_img]], colWidths=[240, 300])
        split_table.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "MIDDLE")]))
        story.append(split_table)
    else:
        story.append(t_alert_sum)

    story.append(Spacer(1, 12))

    # Caseload Listing Table
    story.append(Paragraph(f"Active Assigned Cases Detail ({len(cases)})", section_h2))
    case_headers = ["Case Code", "Interval", "Check-ins", "Latest Score", "Risk Band", "Open Alerts", "Next Follow-up Due"]
    case_rows = [[Paragraph(h, cell_bold) for h in case_headers]]

    for c in cases:
        n_check = len(c.checkins)
        latest_sc = "None"
        latest_bd = "None"
        if n_check > 0:
            last = sorted(c.checkins, key=lambda x: _to_utc(x.created_at))[-1]
            latest_sc = f"{last.distress_score:.1f}" if last.distress_score is not None else "N/A"
            latest_bd = (last.distress_band or "N/A").upper()

        c_alerts = sum(1 for a in c.alerts if (a.status.value if hasattr(a.status, 'value') else str(a.status)) in ("open", "reviewed"))
        next_due = _to_utc(c.next_follow_up_due)
        due_str = next_due.strftime("%Y-%m-%d") if next_due else "None"
        status_str = c.status.value if hasattr(c.status, 'value') else str(c.status)
        if next_due and next_due < now and status_str == "active":
            due_str += " (OVERDUE)"

        case_rows.append([
            Paragraph(f"<b>{c.case_code}</b>", cell_style),
            Paragraph(f"{c.follow_up_interval_days}d", cell_style),
            Paragraph(str(n_check), cell_style),
            Paragraph(latest_sc, cell_bold),
            Paragraph(latest_bd, cell_style),
            Paragraph(str(c_alerts), cell_bold if c_alerts > 0 else cell_style),
            Paragraph(due_str, cell_style),
        ])

    t_cases = Table(case_rows, colWidths=[80, 50, 60, 75, 75, 75, 125])
    t_cases.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e2e8f0")),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ])
    )
    story.append(t_cases)

    story.append(Spacer(1, 16))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#cbd5e1"), spaceAfter=8))
    story.append(Paragraph(DISCLAIMER_TEXT, disclaimer_style))

    # Build PDF
    doc.build(story)
    pdf_bytes = buffer.getvalue()
    buffer.close()

    return Response(
        content=pdf_bytes,
        media_type="application/pdf",
        headers={"Content-Disposition": 'attachment; filename="caseload_summary_report.pdf"'},
    )
